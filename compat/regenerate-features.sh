#!/bin/sh
set -eu
repo=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$repo"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT HUP INT TERM
protoc -I protobuf --edition_defaults_out="$tmp/defaults.bin" --edition_defaults_minimum=PROTO2 --edition_defaults_maximum=2026 google/protobuf/descriptor.proto
python3 - "$tmp/defaults.bin" "${1:-internal/semantics/defaults.gen.go}" <<'PY'
import pathlib,sys
b=pathlib.Path(sys.argv[1]).read_bytes()
p=pathlib.Path(sys.argv[2])
p.write_text('// Code generated by compat/regenerate-features.sh with protoc 36.2. DO NOT EDIT.\npackage semantics\n\nvar compiledDefaults = []byte{'+','.join(str(x) for x in b)+'}\n')
PY
gofmt -w "${1:-internal/semantics/defaults.gen.go}"
